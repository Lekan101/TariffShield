#!/usr/bin/env tsx
/**
 * scripts/check-dep-graph.ts
 *
 * Drift check for the committed dependency-graph artifact. Regenerates the
 * graph with scripts/dep-graph.ts, renders it with Graphviz, and compares the
 * result against docs/dep-graph.svg. Exits non-zero when they differ or when
 * the committed file is missing, so a forgotten `make dep-graph` is caught
 * before review.
 *
 * Non-blocking when Graphviz is unavailable: prints an install hint and exits 0
 * so contributors or CI images without `dot` are not hard-blocked (a follow-up
 * will add Graphviz to the default CI image and make this a required gate).
 *
 * Usage:
 *   npm run check:dep-graph
 *   make check-dep-graph
 */

import { execFileSync, spawnSync } from "node:child_process";
import * as fs from "node:fs";
import * as path from "node:path";

const root = process.cwd();
const svgPath = path.join(root, "docs", "dep-graph.svg");
const REGENERATE_HINT =
  "Run `make dep-graph` (or `npm run dep-graph -- --format dot | dot -Tsvg -o docs/dep-graph.svg`) and commit the result.";
const GRAPHVIZ_HINT =
  "Install Graphviz: Debian/Ubuntu `sudo apt-get install -y graphviz`; macOS `brew install graphviz`.";

function graphvizAvailable(): boolean {
  const probe = spawnSync("dot", ["-V"], { encoding: "utf-8" });
  return !probe.error && probe.status === 0;
}

function generateDot(): string {
  return execFileSync("npm", ["run", "--silent", "dep-graph", "--", "--format", "dot"], {
    cwd: root,
    encoding: "utf-8",
  });
}

function renderSvg(dotSource: string): string {
  const rendered = spawnSync("dot", ["-Tsvg"], { input: dotSource, encoding: "utf-8" });
  if (rendered.error) {
    throw rendered.error;
  }
  if (rendered.status !== 0) {
    throw new Error(rendered.stderr || "Graphviz `dot` exited with a non-zero status.");
  }
  return rendered.stdout;
}

/**
 * Drop the `<!-- Generated by graphviz version … -->` header so the comparison
 * is not sensitive to the exact Graphviz build used to render the file.
 */
function stripGeneratorComment(svg: string): string {
  return svg
    .split("\n")
    .filter((line) => !line.trimStart().startsWith("<!-- Generated by graphviz"))
    .join("\n")
    .trim();
}

function main(): void {
  if (!graphvizAvailable()) {
    console.warn(
      "WARN: Graphviz `dot` is not installed — skipping dep-graph drift check (non-blocking).",
    );
    console.warn(GRAPHVIZ_HINT);
    return;
  }

  const expected = renderSvg(generateDot());

  if (!fs.existsSync(svgPath)) {
    console.error(
      "FAIL: docs/dep-graph.svg is missing. " + REGENERATE_HINT,
    );
    process.exit(1);
  }

  const committed = stripGeneratorComment(fs.readFileSync(svgPath, "utf-8"));
  const regenerated = stripGeneratorComment(expected);

  if (committed !== regenerated) {
    console.error("FAIL: docs/dep-graph.svg is out of date. " + REGENERATE_HINT);
    process.exit(1);
  }

  console.log("OK: docs/dep-graph.svg is in sync with scripts/dep-graph.ts.");
}

main();
